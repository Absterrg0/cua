//! Build-time extension trust configuration.
//!
//! Production builds embed exactly one publisher trust root. It defaults to
//! Cua's publisher. A downstream distribution that signs its own extension
//! catalogs supplies a complete replacement root through all six
//! `CUA_DRIVER_EXTENSION_*` variables below; a partial override fails the
//! build instead of silently mixing roots. The root cannot be changed at
//! runtime or by a catalog.

use std::fmt::Write as _;

const OVERRIDE_VARIABLES: [&str; 6] = [
    "CUA_DRIVER_EXTENSION_PUBLISHER_ID",
    "CUA_DRIVER_EXTENSION_PUBLISHER_NAME",
    "CUA_DRIVER_EXTENSION_KEY_ID",
    "CUA_DRIVER_EXTENSION_PUBLIC_KEY_BASE64",
    "CUA_DRIVER_EXTENSION_KEY_VALID_FROM_UNIX",
    "CUA_DRIVER_EXTENSION_KEY_VALID_UNTIL_UNIX",
];

struct PublisherRoot {
    publisher_id: String,
    publisher_name: String,
    key_id: String,
    public_key: [u8; 32],
    valid_from_unix: u64,
    valid_until_unix: u64,
}

fn cua_root() -> PublisherRoot {
    PublisherRoot {
        publisher_id: "cua".to_owned(),
        publisher_name: "Cua".to_owned(),
        key_id: "cua-extension-ed25519-2026-09".to_owned(),
        // The corresponding private key is held outside this repository.
        public_key: [
            0xe9, 0x2d, 0xf5, 0x3e, 0x93, 0x1b, 0x89, 0xe6, 0x86, 0x8a, 0xba, 0x65, 0xe6, 0xbd,
            0xec, 0x35, 0x19, 0x6c, 0x57, 0x5b, 0x9f, 0x38, 0xfc, 0xb0, 0xe8, 0x8b, 0x74, 0xa3,
            0x19, 0x8d, 0x92, 0x8a,
        ],
        valid_from_unix: 1_790_208_000,  // 2026-09-24
        valid_until_unix: 2_082_758_400, // 2036-01-01
    }
}

fn main() {
    println!("cargo:rerun-if-env-changed=CUA_DRIVER_REVIEW_EXTENSION_PUBLIC_KEY_BASE64");
    for name in OVERRIDE_VARIABLES {
        println!("cargo:rerun-if-env-changed={name}");
    }
    validate_review_trust_root_build();
    let root = publisher_root();
    let mut generated = String::new();
    writeln!(generated, "// @generated by cua-driver-extensions/build.rs").unwrap();
    writeln!(generated, "const BUILD_PUBLISHER_ID: &str = {:?};", root.publisher_id).unwrap();
    writeln!(generated, "const BUILD_PUBLISHER_NAME: &str = {:?};", root.publisher_name).unwrap();
    writeln!(generated, "const BUILD_KEY_ID: &str = {:?};", root.key_id).unwrap();
    writeln!(generated, "const BUILD_KEY_VALID_FROM_UNIX: u64 = {};", root.valid_from_unix).unwrap();
    writeln!(generated, "const BUILD_KEY_VALID_UNTIL_UNIX: u64 = {};", root.valid_until_unix).unwrap();
    writeln!(generated, "const BUILD_PUBLIC_KEY: [u8; 32] = {:?};", root.public_key).unwrap();
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("publisher_root.rs"), generated).expect("write publisher_root.rs");
}

fn publisher_root() -> PublisherRoot {
    let values: Vec<Option<String>> = OVERRIDE_VARIABLES
        .iter()
        .map(|name| std::env::var(name).ok().filter(|value| !value.trim().is_empty()))
        .collect();
    if values.iter().all(Option::is_none) {
        return cua_root();
    }
    if values.iter().any(Option::is_none) {
        let missing: Vec<&str> = OVERRIDE_VARIABLES
            .iter()
            .zip(&values)
            .filter(|(_, value)| value.is_none())
            .map(|(name, _)| *name)
            .collect();
        panic!("a distribution publisher root must set all six variables; missing {missing:?}");
    }
    let value = |index: usize| values[index].as_deref().unwrap().trim().to_owned();
    let identifier = |index: usize| {
        let text = value(index);
        if text.len() > 64
            || !text
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.'))
        {
            panic!("{} must be 1-64 characters of [A-Za-z0-9._-]", OVERRIDE_VARIABLES[index]);
        }
        text
    };
    let publisher_id = identifier(0);
    let key_id = identifier(2);
    let publisher_name = value(1);
    if publisher_name.len() > 128 || publisher_name.chars().any(char::is_control) {
        panic!("CUA_DRIVER_EXTENSION_PUBLISHER_NAME must be at most 128 printable characters");
    }
    if publisher_id == "cua" || publisher_id.starts_with("cua-review") {
        panic!("a distribution publisher root must not reuse Cua's publisher identity");
    }
    let public_key = decode_key(&value(3))
        .unwrap_or_else(|| panic!("CUA_DRIVER_EXTENSION_PUBLIC_KEY_BASE64 must be standard base64 for one 32-byte Ed25519 key"));
    let number = |index: usize| {
        value(index)
            .parse::<u64>()
            .unwrap_or_else(|_| panic!("{} must be a Unix timestamp", OVERRIDE_VARIABLES[index]))
    };
    let valid_from_unix = number(4);
    let valid_until_unix = number(5);
    if valid_from_unix >= valid_until_unix {
        panic!("the publisher key validity window is empty");
    }
    PublisherRoot {
        publisher_id,
        publisher_name,
        key_id,
        public_key,
        valid_from_unix,
        valid_until_unix,
    }
}

fn decode_key(text: &str) -> Option<[u8; 32]> {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let bytes = text.as_bytes();
    if bytes.len() != 44 || bytes[43] != b'=' || bytes[42] == b'=' {
        return None;
    }
    let mut bits = 0u32;
    let mut count = 0;
    let mut out = Vec::with_capacity(33);
    for &byte in &bytes[..43] {
        let index = ALPHABET.iter().position(|&candidate| candidate == byte)? as u32;
        bits = (bits << 6) | index;
        count += 6;
        if count >= 8 {
            count -= 8;
            out.push((bits >> count) as u8);
            bits &= (1 << count) - 1;
        }
    }
    if bits != 0 || out.len() != 32 {
        return None;
    }
    out.try_into().ok()
}
fn validate_review_trust_root_build() {
    if std::env::var_os("CARGO_FEATURE_REVIEW_TRUST_ROOT").is_none() {
        return;
    }
    if std::env::var("PROFILE").as_deref() == Ok("release") {
        panic!("review-trust-root is review-only and cannot be enabled in release artifacts");
    }
    let key = std::env::var("CUA_DRIVER_REVIEW_EXTENSION_PUBLIC_KEY_BASE64").expect(
        "review-trust-root requires CUA_DRIVER_REVIEW_EXTENSION_PUBLIC_KEY_BASE64 at build time",
    );
    let key = key.trim().as_bytes();
    if key.len() != 44
        || key[43] != b'='
        || !key[..43]
            .iter()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'+' | b'/'))
    {
        panic!("review-trust-root override must be standard base64 for exactly one 32-byte Ed25519 public key");
    }
}

